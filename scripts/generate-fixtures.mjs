#!/usr/bin/env node
/**
 * Turns the examples already written into the API contract into typed fixtures.
 *
 * One source of truth: the mock server, the fixture backend the app can run against and
 * the tests all read the same examples, so none of them can quietly drift from the
 * contract the client is generated from.
 */
import { readFileSync, writeFileSync } from 'node:fs';

import { parse } from 'yaml';

const CONTRACT = 'src/contract/openapi.yaml';
const OUTPUT = 'src/mocks/generated/fixtures.ts';

const contract = parse(readFileSync(CONTRACT, 'utf8'));

/** OpenAPI path templating to a regular expression that captures each parameter. */
function toPattern(path) {
  const names = [];
  const source = path.replace(/\{([^}]+)\}/g, (_, name) => {
    names.push(name);
    return '([^/]+)';
  });
  return { source: `^${source}$`, names };
}

/** Follows a $ref into the components section. */
function resolve(schema) {
  if (!schema || typeof schema !== 'object') return schema;
  if (!schema.$ref) return schema;

  const name = schema.$ref.replace('#/components/schemas/', '');
  return resolve(contract.components.schemas[name]);
}

/**
 * Builds the example a schema describes, the way a mock server would.
 *
 * A schema may carry its own example, or be composed from the examples on its parts: a
 * page is its envelope plus one of the item examples, a session is its user plus its
 * tokens. Anything with nothing to go on returns undefined rather than an empty shell.
 */
function exampleFor(schema, depth = 0) {
  const resolved = resolve(schema);
  if (!resolved || typeof resolved !== 'object' || depth > 8) return undefined;

  if (resolved.example !== undefined) return resolved.example;
  if (Array.isArray(resolved.examples) && resolved.examples.length > 0) return resolved.examples[0];

  if (Array.isArray(resolved.allOf)) {
    const parts = resolved.allOf.map((part) => exampleFor(part, depth + 1));
    const objects = parts.filter((part) => part && typeof part === 'object');
    return objects.length > 0 ? Object.assign({}, ...objects) : undefined;
  }

  if (resolved.items) {
    const item = exampleFor(resolved.items, depth + 1);
    return item === undefined ? undefined : [item];
  }

  if (resolved.properties) {
    const composed = {};
    for (const [name, property] of Object.entries(resolved.properties)) {
      const value = exampleFor(property, depth + 1);
      if (value !== undefined) composed[name] = value;
    }
    return Object.keys(composed).length > 0 ? composed : undefined;
  }

  return undefined;
}

function successExample(operation) {
  const responses = operation.responses ?? {};
  const status = Object.keys(responses)
    .filter((code) => code.startsWith('2'))
    .sort()[0];
  if (!status) return null;

  const content = responses[status].content ?? {};
  const media = content['application/json'];
  if (!media) return { status: Number(status), example: undefined };

  // A media-type example wins over the schema's, matching how Prism resolves them.
  const example = media.example ?? exampleFor(media.schema);
  return { status: Number(status), example };
}

const operations = [];

for (const [path, item] of Object.entries(contract.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!['get', 'post', 'patch', 'put', 'delete'].includes(method)) continue;

    const found = successExample(operation);
    if (!found) continue;

    const { source, names } = toPattern(path);
    operations.push({
      operationId: operation.operationId,
      method: method.toUpperCase(),
      path,
      pattern: source,
      params: names,
      status: found.status,
      example: found.example,
    });
  }
}

operations.sort((a, b) => a.operationId.localeCompare(b.operationId));

const withExample = operations.filter((operation) => operation.example !== undefined);

const lines = [
  '// Generated by `npm run fixtures` from src/contract/openapi.yaml. Do not edit.',
  '// Every value here is an example taken from the contract itself.',
  '',
  'export type FixtureRoute = {',
  '  operationId: string;',
  '  method: string;',
  '  /** OpenAPI path, kept for error messages. */',
  '  path: string;',
  '  /** Anchored pattern matching a request path, with one group per parameter. */',
  '  pattern: string;',
  '  params: string[];',
  '  status: number;',
  '};',
  '',
  'export const fixtureRoutes: FixtureRoute[] = [',
  ...operations.map(
    (operation) =>
      `  { operationId: ${JSON.stringify(operation.operationId)}, method: ${JSON.stringify(
        operation.method,
      )}, path: ${JSON.stringify(operation.path)}, pattern: ${JSON.stringify(
        operation.pattern,
      )}, params: ${JSON.stringify(operation.params)}, status: ${operation.status} },`,
  ),
  '];',
  '',
  '/** Response bodies, keyed by operation. Absent means the operation returns no content. */',
  'export const fixtureBodies: Record<string, unknown> = {',
  ...withExample.map(
    (operation) =>
      `  ${JSON.stringify(operation.operationId)}: ${JSON.stringify(operation.example)},`,
  ),
  '};',
  '',
];

writeFileSync(OUTPUT, lines.join('\n'));

console.log(`Wrote ${OUTPUT}`);
console.log(`  ${operations.length} operations, ${withExample.length} with an example`);
const missing = operations.filter((operation) => operation.example === undefined);
if (missing.length > 0) {
  console.log(`  no example for: ${missing.map((entry) => entry.operationId).join(', ')}`);
}
